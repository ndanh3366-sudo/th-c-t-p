function generate25Reviews(prodId: string) {
  return REVIEW_COMMENTS_TEMPLATE.map((comment, index) => {
    const day = String(28 - (index % 25)).padStart(2, '0');
    return {
      id: `rev-${prodId}-${index + 1}`,
      userName: REVIEW_USER_NAMES[index % REVIEW_USER_NAMES.length],
      rating: index % 7 === 0 ? 4 : 5,
      date: `${day}/07/2026`,
      comment: comment,
      verifiedPurchase: true
    };
  });
}

function generate25QAs(prodId: string) {
  return QA_QUESTIONS_TEMPLATE.map((qa, index) => {
    const day = String(28 - (index % 25)).padStart(2, '0');
    return {
      id: `qa-${prodId}-${index + 1}`,
      question: qa.q,
      askedBy: REVIEW_USER_NAMES[(index + 3) % REVIEW_USER_NAMES.length],
      answer: qa.a,
      answeredBy: 'NPTTEAMSTORE Technical Team',
      date: `${day}/07/2026`
    };
  });
}

